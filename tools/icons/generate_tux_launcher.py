#!/usr/bin/env python3
"""Build launcher vectors/legacy PNGs from the Easter egg's native Tux face.
Needs rsvg-convert, Pillow and numpy. No image service or network is used.
"""
from pathlib import Path
import copy, re, subprocess, tempfile, xml.etree.ElementTree as E
from PIL import Image, ImageDraw
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / 'app/src/main/res'
OUT = ROOT / 'artwork/launcher'
A = '{http://schemas.android.com/apk/res/android}'
E.register_namespace('android', A[1:-1])
E.register_namespace('aapt', 'http://schemas.android.com/aapt')
SOURCE = RES / 'drawable/tux_listener.xml'
NOTE = '<!-- Generated by tools/icons/generate_tux_launcher.py. Tux: Larry Ewing / The GIMP; Arris redraw GPL-3.0. -->\n'
BG = '#103126'

def path(d, fill, **attrs):
    return E.Element('path', {A+'pathData':d, A+'fillColor':fill, **{A+k:str(v) for k,v in attrs.items()}})

def body():
    return path('M85 128C67 139 56 161 60 178C78 196 109 205 140 205C174 205 205 193 220 178C224 158 209 137 196 128Z', '#1C2A24')

def face():
    original=E.parse(SOURCE).getroot()[0][0]
    g=E.Element('group')
    g.append(body())
    g.append(path('M98 144Q140 125 183 145L191 183Q140 208 88 183Z','#F4E8C9'))
    for i in [5,6,7,8,9,12,13,14,15,16]: g.append(copy.deepcopy(original[i]))
    return g

def monochrome():
    # Negative-space eye/beak details stay readable after the system tints alpha.
    g=E.Element('group')
    g.append(path('M85 128C67 139 56 161 60 178C78 196 109 205 140 205C174 205 205 193 220 178C224 158 209 137 196 128Z M110 157Q140 148 172 157L176 180Q140 193 105 180Z','#FFFFFF',fillType='evenOdd'))
    head='M72 103Q63 59 87 28Q106 5 139 7Q178 6 198 32Q219 59 207 111Q198 147 140 149Q80 145 72 103Z'
    eyes='M110 75a9 14 0 1 0 18 0a9 14 0 1 0 -18 0Z M156 75a9 14 0 1 0 18 0a9 14 0 1 0 -18 0Z'
    beak='M109 103Q140 85 174 103Q166 125 142 126Q121 125 109 103Z'
    g.append(path(head+' '+eyes+' '+beak,'#FFFFFF',fillType='evenOdd'))
    g.append(path('M61 81Q60 1 140 0Q219 1 218 81','#00000000',strokeColor='#FFFFFF',strokeWidth=13,strokeLineCap='round'))
    original=E.parse(SOURCE).getroot()[0][0]
    for i in [14,15]:
        p=copy.deepcopy(original[i]);p.set(A+'fillColor','#FFFFFF');g.append(p)
    return g

# Centre the same source face at 140,96. The full silhouette stays inside r=34.
SCALE=.29
TX=54-140*SCALE
TY=54-96*SCALE

def group(content):
    g=E.Element('group',{A+'scaleX':str(SCALE),A+'scaleY':str(SCALE),A+'translateX':str(TX),A+'translateY':str(TY)})
    g.append(copy.deepcopy(content));return g

def vector(content, name, width=108, height=108, viewport=108):
    v=E.Element('vector',{A+'width':f'{width}dp',A+'height':f'{height}dp',A+'viewportWidth':str(viewport),A+'viewportHeight':str(viewport)})
    if isinstance(content,list):v.extend(content)
    else:v.append(content)
    E.indent(v)
    (RES/f'drawable/{name}.xml').write_text('<?xml version="1.0" encoding="utf-8"?>\n'+NOTE+E.tostring(v,encoding='unicode')+'\n')

SVG_ATTR={'pathData':'d','fillColor':'fill','fillAlpha':'fill-opacity','strokeColor':'stroke','strokeWidth':'stroke-width','strokeLineCap':'stroke-linecap','strokeAlpha':'stroke-opacity','fillType':'fill-rule'}
def svg_element(el):
    if el.tag=='group':
        g=E.Element('g');tx=el.get(A+'translateX','0');ty=el.get(A+'translateY','0');sx=el.get(A+'scaleX','1');sy=el.get(A+'scaleY','1')
        g.set('transform',f'translate({tx} {ty}) scale({sx} {sy})')
        for c in el:g.append(svg_element(c))
        return g
    p=E.Element('path')
    for k,v in el.attrib.items():
        key=k.removeprefix(A)
        if key in SVG_ATTR:
            if v=='#00000000':v='none'
            if key=='fillType' and v=='evenOdd':v='evenodd'
            p.set(SVG_ATTR[key],v)
    return p

def svg(content,bg=False,mask=None,view='0 0 108 108'):
    root=E.Element('svg',{'xmlns':'http://www.w3.org/2000/svg','viewBox':view,'width':'108','height':'108'})
    if mask:
        defs=E.SubElement(root,'defs');clip=E.SubElement(defs,'clipPath',{'id':'mask'})
        if mask=='circle':E.SubElement(clip,'circle',{'cx':'54','cy':'54','r':'36'})
        elif mask=='square':E.SubElement(clip,'rect',{'x':'18','y':'18','width':'72','height':'72','rx':'14'})
        else:E.SubElement(clip,'path',{'d':'M54 18C81 18 90 27 90 54S81 90 54 90S18 81 18 54S27 18 54 18Z'})
    layer=E.SubElement(root,'g',{'clip-path':'url(#mask)'} if mask else {})
    if bg:E.SubElement(layer,'rect',{'width':'108','height':'108','fill':BG})
    layer.append(svg_element(content))
    return E.tostring(root,encoding='unicode')

def render(svg_text,px,out):
    subprocess.run(['rsvg-convert','-w',str(px),'-h',str(px),'-o',str(out)],input=svg_text.encode(),check=True)


def main():
    OUT.mkdir(parents=True,exist_ok=True)
    colors=RES/'values/colors.xml'
    colors.write_text(re.sub(r'(<color name="ic_launcher_background">).*?(</color>)',r'\g<1>'+BG+r'\g<2>',colors.read_text()))
    fg=group(face());mono=group(monochrome())
    vector(fg,'ic_launcher_foreground');vector(mono,'ic_launcher_monochrome')
    vector(path('M0 0H108V108H0Z',BG),'ic_launcher_background')
    # About/splash use the same centre 72dp framing as an adaptive mask.
    about=E.Element('group',{A+'scaleX':'1.5',A+'scaleY':'1.5',A+'translateX':'-27',A+'translateY':'-27'})
    about.append(path('M18 54a36 36 0 1 0 72 0a36 36 0 1 0 -72 0Z',BG));about.append(copy.deepcopy(fg))
    vector(about,'ic_launcher',width=192,height=192)
    small=E.Element('group',{A+'scaleX':str(1/3),A+'scaleY':str(1/3),A+'translateX':'-6',A+'translateY':'-6'})
    small.append(copy.deepcopy(mono));vector(small,'ic_tux_notification',width=24,height=24,viewport=24)
    for name in ['ic_launcher','ic_launcher_round']:
        p=RES/f'mipmap-anydpi-v26/{name}.xml'
        p.write_text('<?xml version="1.0" encoding="utf-8"?>\n'+NOTE+'''<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
''')
    (OUT/'tux-launcher.svg').write_text(svg(fg,True,'circle','18 18 72 72'))
    (OUT/'tux-monochrome.svg').write_text(svg(mono,False,None,'18 18 72 72'))
    with tempfile.TemporaryDirectory() as td:
        alpha=Path(td)/'alpha.png';render(svg(fg),1080,alpha)
        a=np.asarray(Image.open(alpha))[:,:,3];yy,xx=np.where(a>16)
        radius=np.sqrt(((xx+.5)/10-54)**2+((yy+.5)/10-54)**2).max()
        assert radius <= 34, f'adaptive safe radius exceeded: {radius}'
        print(f'Foreground radius {radius:.3f}dp <=34dp; no opaque pixels are cropped by the circular safe zone.')
        for density,size in {'mdpi':48,'hdpi':72,'xhdpi':96,'xxhdpi':144,'xxxhdpi':192}.items():
            for rounded,name in [(False,'ic_launcher'),(True,'ic_launcher_round')]:
                text=svg(fg,True,'circle' if rounded else 'square','18 18 72 72')
                render(text,size,RES/f'mipmap-{density}/{name}.png')
        sheet=Image.new('RGB',(800,430),'#e9ede8');d=ImageDraw.Draw(sheet)
        for i,(label,shape,content) in enumerate([('Circle','circle',fg),('Rounded square','square',fg),('Squircle','squircle',fg),('Themed','circle',mono)]):
            tmp=Path(td)/f'{i}.png';render(svg(content,True,shape,'18 18 72 72'),160,tmp)
            im=Image.open(tmp).convert('RGBA');sheet.paste(im,(20+i*200,30),im);d.text((25+i*200,205),label,fill='#20362b')
            for j,size in enumerate([48,32,24]):
                tmp=Path(td)/f'{i}-{size}.png';render(svg(content,True,shape,'18 18 72 72'),size,tmp)
                im=Image.open(tmp).convert('RGBA');sheet.paste(im,(25+i*200+j*55,260),im)
            d.text((25+i*200,330),'48px / 32px / 24px',fill='#20362b')
        sheet.save(OUT/'preview.png')
        (OUT/'geometry.txt').write_text(f'Source: app/src/main/res/drawable/tux_listener.xml\nForeground maximum alpha radius: {radius:.3f}dp\nSafety threshold: 34dp\nGenerated with rsvg-convert and Pillow.\n')

if __name__=='__main__':main()
