package com.takahashirinta.ncrust.ui.player.waveform

import kotlin.math.abs
import kotlin.math.cos
import kotlin.math.exp
import kotlin.math.sin
import kotlin.math.sqrt

/**
 * v3.4.5：**柱高与小球的两个物理模型**（纯逻辑，JVM 可直接单测，零分配）。
 *
 * 用户原话：「抖动还是有，**小球没有弹起来的感觉**，我觉得这个地方小球上下运动的函数
 * 要不就用**牛顿运动学公式**，和**弹性碰撞的公式**来做吧」。
 *
 * 这一版之前，画面上的两个纵向运动都是**非物理**的：
 *
 * | 元素 | 旧写法 | 缺陷 |
 * |---|---|---|
 * | 柱高（色带顶边 / 圆点所在的那条包络） | `current += (target-current) * (1-exp(-dt/tau))` | 指数逼近：渐近、永不越冲、永不回弹，且 `SETTLE_EPSILON` 收敛截断让它在接近目标时**直接吸附** |
 * | 峰值标记（`peaks[]`，画在色带上方的小球/短横） | 保持 420ms 后**匀速**下落，落到柱高就停 | 匀速 = 零加速度；落到柱高即停 = **永不反弹** |
 *
 * 现在换成两个有明确力学依据的模型，**单位统一是「归一化高度 / 秒」**
 * （画面高度 1.0 = 满幅；`BAR_DOT_RADIUS_DP` 那类像素量在渲染层换算，不参与物理）。
 *
 * ## 1. 柱高：[SpringStep] —— 二阶系统（弹簧-阻尼）的**精确解**
 *
 * 牛顿第二定律，把柱高 x 当作一个挂在目标位上的阻尼振子：
 *
 * ```
 * x'' = ω²·(target − x) − 2ζω·x'
 * ```
 *
 * - **不用数值积分（欧拉/半隐式）**：那会让 60Hz 与 146Hz 走出两条不同的曲线
 *   （本仓库的硬契约之一就是「与刷新率无关」）。这里用欠阻尼二阶系统的**闭式解**：
 *   `x(t) = target + e^(−ζωt)·(A·cos ω_d t + B·sin ω_d t)`，`ω_d = ω√(1−ζ²)`。
 *   闭式解对任意 `dt` 都**精确**，所以 60Hz / 146Hz / 30Hz 得到的是同一条轨迹
 *   （只在采样点上不同），不是"误差很小"而是"没有离散误差"。
 * - **系数每帧只算一次**（`e^(−ζω·dt)`、`cos`、`sin` 三个超越函数），
 *   然后所有格子共用 —— `barCount=28` × 4 条窗口也不会变成每格一次 `exp`。
 *
 * ### 参数依据（不是拍脑袋）
 *
 * - **ω（自然频率）取自旧实现的时间常数**：旧代码起音 τ=22ms、回落 τ=130ms
 *   （[BandBallistics.ATTACK_TAU_MS] / [RELEASE_TAU_MS]，v1.8.1 就有）。
 *   二阶系统的**包络**时间常数是 `1/(ζω)`，所以令 `ω = 1/(ζ·τ)`，
 *   就得到"上升/回落的快慢与旧版一致"的振子 —— 观感的改变只来自**惯性**与**过冲**，
 *   而不是整体变快或变慢。升 / 降用各自的 ω（`target ≥ x` 用起音、否则用回落）。
 * - **ζ = 0.75**：过冲量 = `exp(−πζ/√(1−ζ²))` = **2.8%**（满幅的 2.8%，约 2~3px，属于"轻微过冲"），
 *   整定时间 ≈ `3/(ζω)` ≈ 70ms（起音）——比一个柱间隔（83~100ms）短，
 *   所以它**不会**把 12Hz 的阶梯糊成晃动。ζ=1（临界阻尼）过冲为 0，看不到"弹"；
 *   ζ≤0.5 过冲 ≥16%，在满幅附近会反复撞 `coerceIn(0,1)`，画面上会"顶到天花板再弹回来"。
 * - **上界**：`coerceIn(0,1)` 依旧是硬契约（PPM 不得为负、柱高不得越幅）。
 *   2.8% 的过冲意味着只有目标已经在 1.0 附近时才会被夹住，夹住的量极小。
 * - **静止吸附**：`|x−target| + |x'|/ω < SETTLE_EPSILON` 时把 `x` 精确置为 target、速度归零。
 *   这一条是「不空转」契约的支点：只要没吸附就继续要求重绘，一旦吸附就**精确相等**、
 *   下一帧自然停（与旧的 `SETTLE_EPSILON` 语义一致，只是判据里多了速度项）。
 *
 * ## 2. 小球：[BallStep] —— 牛顿自由落体 + 与柱顶的弹性碰撞
 *
 * 状态 = 位置 `y`（归一化高度，向上为正）、速度 `v`、以及"是否静止在地面上"。
 * **柱顶就是地面**（`ground` = 该格的柱高画面值，`groundV` = 该格柱高的速度）。
 *
 * 每帧（v3.4.6 的顺序，`resting` 只在"贴住地面"时有意义）：
 * ```
 * 若 静止 且 贴住地面：
 *     若 groundV >  KICK_MIN_V   ⇒ 被柱顶顶起（v ← min(groundV, V_KICK_MAX)）
 *     若 groundV < −DETACH_MIN_V ⇒ ★ 脱离地面（v = 0，清静止标志）—— 本帧到此为止
 *     否则                       ⇒ 被地面托着走（y = ground，v = 0）
 * 否则：
 *     y ← y + v·dt − ½·g·dt²   （常加速度的**精确解**，不是欧拉法）
 *     v ← v − g·dt
 *     若 y ≤ ground ⇒ 接触：
 *         y = ground                                    （绝不穿进柱子 —— 硬契约）
 *         v ← −e·v                                      （弹性碰撞，e = RESTITUTION）
 *         若地面比它快 ⇒ v ← max(v, min(groundV, V_KICK_MAX))（被柱顶"顶起"）
 *         若反弹顶点不可见 ⇒ v = 0 且标记为静止（吸附）
 * ```
 *
 * ★ **「脱离地面」是 v3.4.6 补上的那一支**。在它之前，静止的小球在"贴住地面"时
 * 位置被**无条件**设为 `ground`、速度归零 —— 柱子一落，小球就被刚体平移着带下去。
 * 用户实测原话：「**就是粘在顶上一起平移，短线也是，一点都不真实**」。
 * 物理上柱顶只能**推**小球、不能**拉**它，所以地面下落得够快时小球必须留在原处下落。
 * 判据与取值理由见 [DETACH_MIN_V]。
 *
 * ### 参数依据
 *
 * 三个常量的来龙去脉都写在各自的 KDoc 上（v3.4.6 重标定了两个）：
 *
 * - **g = 10 /s²**（旧 32）：旧值按"满幅落到 0 用 250ms"反解，但那个口径测错了对象 ——
 *   小球日常只有一个顶点（0.2）的行程，按 32 算只有 112ms，肉眼读成"跳了一下"。
 *   现在按**顶点行程的滞空时间**定标（上升 200ms）。详见 [GRAVITY]。
 * - **e = 0.7**（旧 0.45）：`e² = 0.49`，从 0.2 起跳的后继顶点
 *   `0.098 / 0.048 / 0.024 / 0.011 / 0.006` —— 按 2% 满幅的感知门槛算有**三跳看得见**
 *   （旧值只有一跳）。详见 [RESTITUTION]。
 * - **顶起（kick）**：柱子升高撞上小球时，小球继承地面速度，但**上限**
 *   `V_KICK_MAX = √(2·g·KICK_APEX_MAX)`，`KICK_APEX_MAX = 0.2`（用户定的顶点）。
 *   理由：完全非弹性正碰（小球取地面速度）在物理上是对的，但柱高的弹簧速度可以到
 *   `ω·Δ ≈ 57/s`，直接继承会把小球甩出画布十几倍高。上限的物理读法是
 *   "柱子的等效质量有限 / 接触不是无穷刚"，工程读法是"顶点必须留在画幅内"。
 *   上限**只加在"被地面顶起"这一项上**，不夹自由落体的反弹 —— 反弹速度由落差决定
 *   （满幅落下也只有 `√(2g) ≈ 4.5`），夹它只会把大落差的一跳压平。
 *   低于 `KICK_MIN_V` 的缓慢上升**不顶起**，小球只是被地面托着走 ——
 *   否则静止的小球会被地面的微动一直弹，那就又变成抖动了。
 * - **静止判据**用**顶点高度**而不是速度阈值：`v²/(2g) < REST_APEX`（0.15% 满幅 ≈ 0.13px）。
 *   这一点很关键 —— 重力每帧都会给小球 `g·dt` 的速度，若用固定速度阈值，
 *   60Hz 与 146Hz 会得到不同结论，且低帧率下小球会**永远微跳**、
 *   `pump` 永远返回 true（"不空转"契约当场失效）。
 *   静止态下**不施加重力**（地面的法向力抵消它），这是"停得住"的物理原因。
 *   注意 [DETACH_MIN_V] 的存在正是为了让"脱离"不与这条契约打架：地面速度趋近 0 时
 *   小球仍然走"托着走"、精确吸附，不会在柱顶上抖出一串看不见的微跳。
 *
 * ## 零分配
 *
 * 两个类都是**每实例零分配**：`step` 只读写调用方传进来的 `out` 数组与自己的
 * 标量字段，不建对象、不建集合、不捕获 lambda。`WaveformRing` 每个窗口持有
 * **一个** `SpringStep` / `BallStep` 实例（构造期建好）与**一个** `FloatArray` 暂存区，
 * 帧路径上反复复用（见 `WaveformRingTest` 的 `物理步进器复用同一批数组` 用例）。
 */
object BandBallistics {

    // ───────────────────────── 柱高：二阶系统 ─────────────────────────

    /** 阻尼比。过冲 `exp(−πζ/√(1−ζ²))` = 2.8%。取值理由见类 KDoc。 */
    const val DAMPING_RATIO = 0.75f

    /** 起音包络时间常数（毫秒）—— 沿用 v1.8.1 的值，保证"快慢"没有变。 */
    const val ATTACK_TAU_MS = 22f

    /** 回落包络时间常数（毫秒）—— 同上。 */
    const val RELEASE_TAU_MS = 130f

    /** 静止吸附阈值（归一化高度）。与旧的 `SETTLE_EPSILON` 同值。 */
    const val SETTLE_EPSILON = 0.004f

    /**
     * 由包络时间常数反解自然频率：二阶系统的包络是 `e^(−ζωt)`，所以 `ζω = 1/τ`。
     */
    fun omegaFor(tauMs: Float): Float =
        if (tauMs <= 0f) 1f else 1f / (DAMPING_RATIO * (tauMs / 1000f))

    // ───────────────────────── 小球：自由落体 + 弹性碰撞 ─────────────────────────

    /**
     * 重力加速度（归一化高度/秒²）。
     *
     * ## v3.4.6：32 → 10（用户实测「落地好快」）
     *
     * 用户原话：「**小球落地好快啊，完全就像是僵硬的平移到下一帧**，感觉可能是
     * 重力加速度太大，并且没有运算后面连续的弹性碰撞」。
     *
     * 32 是按「从满幅 1.0 落到 0 用 250ms」反解的（`2·1.0/0.25² = 32`）——
     * 但那个口径**测错了对象**：小球日常并不是从满幅落下，它的典型行程只有一个
     * 「顶点」（[KICK_APEX_MAX] = 0.2）。按 32 计算，0.2 的行程只有
     * `√(2×0.2/32) = 112ms`（≈6.7 帧 @60Hz）就落完 —— 一帧走 4.6% 满幅，
     * 肉眼读到的就是"跳了一下"，不是"落下来"。
     *
     * 现在按**顶点行程的滞空时间**定标：要让 0.2 的起落读得出来，取上升 200ms
     * ⇒ `g = 2×0.2/0.2² = 10`。于是：
     *
     * | 行程 | 32（旧） | 10（新） |
     * |---|---|---|
     * | 顶点 0.2 的上升段 | 112ms（≈7 帧） | **200ms（≈12 帧）** |
     * | 顶点 0.2 的完整起落 | 224ms | **400ms** |
     * | 满幅 1.0 落到 0 | 250ms | 447ms |
     *
     * 400ms 的完整起落 ≈ 一个常见拍长，所以「一拍拍一下」的观感是成立的；
     * 而满幅 447ms 只在柱子从上沿整个塌下去时才会出现，不会显得拖沓。
     *
     * ⚠️ 与旧值的关系：`V_KICK_MAX = √(2·g·KICK_APEX_MAX)` 随 g 一起变小
     * （2.77 → 2.00），但**顶点仍然是用户定的 0.2**（那条断言没动）。
     */
    const val GRAVITY = 10f

    /**
     * 恢复系数 `e`。每次碰撞后顶点高度剩 `e²`。
     *
     * ## v3.4.6：0.45 → 0.7（用户实测「没有运算后面连续的弹性碰撞」）
     *
     * 用户原话：「…**并且没有运算后面连续的弹性碰撞**」。旧值 0.45 的
     * `e² = 0.20`：从顶点 0.2 掉下来，后继顶点依次是 `0.040 / 0.008 / 0.0016`。
     *
     * 判"看得见几次"要用**感知阈值**而不是 [REST_APEX]：后者是 0.15% 满幅 ≈ 0.13px，
     * 那是"技术上还在动"，不是"眼睛看得见"。按 **2% 满幅**（波形条约 64dp 高时约 2~4px）
     * 这个感知门槛算，三档的对比是：
     *
     * | e | e² | 从 0.2 起跳的后继顶点 | 感知可见跳数 |
     * |---|---|---|---|
     * | 0.45（旧） | 0.20 | 0.040 / 0.008 / 0.0016 | **1** |
     * | 0.60 | 0.36 | 0.072 / 0.026 / 0.009 | **2** |
     * | **0.70（本版）** | **0.49** | 0.098 / 0.048 / 0.024 / 0.011 / 0.006 | **3** |
     *
     * 0.7 的整串（含首跳）约 `0.82s` 收敛 —— 两次弹跳之间是"越来越矮、越来越快"的
     * 经典橡胶球节奏，既读得出"连续的弹性碰撞"，又不会一直在柱顶上振铃。
     *
     * ## 为什么不能更高
     *
     * `e → 1` 时序列**不收敛**（重力不衰减能量、地面还可能继续顶），小球会在柱顶上
     * 永远抖动 —— 那正是用户更早期抱怨的"抖动"。本值必须让
     * `0.2 · (e²)ⁿ < REST_APEX` 在**有限步**内成立：`e = 0.7` 时 n ≈ 7 步。
     * 单测 `参数依据自检` 用"可见跳数 ≥ 3"把下界钉住，用这个收敛式把上界钉住。
     */
    const val RESTITUTION = 0.7f

    /** 顶点低于这个高度（满幅比例）就认为"看不见了"，吸附静止。 */
    const val REST_APEX = 0.0015f

    /**
     * v3.4.6：**地面塌下去多少才让小球脱离地面**（顶点口径，满幅比例）。
     *
     * 这是本次修复「粘在柱顶一起平移」的判据。旧实现在"静止在地面上"那一支里
     * **无条件**把位置设为地面、速度归零 —— 于是柱子一落，小球就被刚体平移着
     * 带下去，用户实测原话：「**就是粘在顶上一起平移，短线也是，一点都不真实**」。
     *
     * 物理上小球在柱顶上时只能被**推**（法向力），不能被**拉**：地面向上动，
     * 它跟着走；地面向下动得比自由落体还快，它就必须留在原地开始下落。
     *
     * 判据取"回落速度达到多少就让开"，用**顶点口径**表达（与 [KICK_MIN_V] 对称）：
     * `√(2·g·DETACH_APEX)`。0.01 的读法是「地面回落得快到足以让小球凭空落下
     * 1% 满幅」—— 那已经不是"托着走"能解释的量级了。
     *
     * 为什么不取 0：地面在弹簧整定阶段的微小回落（末尾几帧速度趋近 0）会让小球
     * 反复"脱离—落回"，在柱顶上抖出一串看不见的微跳。留一个门槛，
     * 慢速移动的地面仍然走"托着走"，**静止吸附契约（不空转）不受影响**。
     */
    const val DETACH_APEX = 0.01f

    /** 脱离门槛速度：`√(2·g·DETACH_APEX)`。 */
    val DETACH_MIN_V: Float = sqrt(2f * GRAVITY * DETACH_APEX)

    /**
     * 被上升的柱顶顶起时，**踢起初速度**对应的顶点上限（满幅比例）。
     *
     * ⚠️ 语义澄清（我第一版在这里算错过一次）：`v = √(2·g·KICK_APEX_MAX)` 反解回来
     * **正好等于这个常量**，所以它**就是**踢起后的顶点，不需要再乘任何修正系数。
     * （我一度按"参数 0.12 → 实测 0.135"乘了 1.125，但那个 0.135 是别处的观测量，
     *   不是这条判据的值 —— 规范地跑 `BallStep` 得到的是 0.178，与参数严格相等。）
     *
     * **用户定的目标是顶点 ≈ 0.2**（原话「顶点高度改 0.2?」），所以直接取 0.2，
     * 并由 `BandBallisticsTest.顶起目标的实测顶点接近用户要求的零点二` 断言实测值 ——
     * 断言"跑出来的顶点"而不是只断言常量，这样以后有人改常量会立刻红。
     */
    const val KICK_APEX_MAX = 0.2f

    /** 顶起速度上限：`√(2·g·KICK_APEX_MAX)` ≈ 2.77 /s。 */
    val V_KICK_MAX: Float = sqrt(2f * GRAVITY * KICK_APEX_MAX)

    /** 低于这个上升速度就不顶起（只是被地面托着走），避免静止小球被微动弹起来。 */
    val KICK_MIN_V: Float = sqrt(2f * GRAVITY * REST_APEX)

    /** 单帧 dt 的上限（秒）：与 `pump` 的 `coerceIn(0,200)` 一致。 */
    const val MAX_DT_SEC = 0.2f

    /**
     * 二阶系统（弹簧-阻尼）在 `dt` 内的**精确解**推进器。
     *
     * **每帧 `prepare` 一次，然后所有格子共用** —— 三个超越函数只算一次。
     * 实例在构造期创建、字段原地覆盖：帧路径零分配。
     */
    class SpringStep {
        /** 本次 `prepare` 用的自然频率（静止判据要用它把速度折成位移）。 */
        var omega: Float = 1f
            private set

        private var decay = 1f
        private var cosWd = 1f
        private var sinWd = 0f
        private var zetaOmega = 0f
        private var omegaD = 1f

        fun prepare(omega: Float, zeta: Float, dtSec: Float) {
            val w = if (omega.isFinite() && omega > 1e-3f) omega else 1e-3f
            val z = if (zeta.isFinite()) zeta.coerceIn(0f, 0.999f) else DAMPING_RATIO
            val d = if (dtSec.isFinite()) dtSec.coerceIn(0f, MAX_DT_SEC) else 0f
            this.omega = w
            zetaOmega = z * w
            omegaD = w * sqrt(1f - z * z)
            decay = exp(-zetaOmega * d)
            val ang = omegaD * d
            cosWd = cos(ang)
            sinWd = sin(ang)
        }

        /**
         * 推进一格。
         *
         * @param out 长度 ≥ 2 的复用数组：`out[0]` = 新位置、`out[1]` = 新速度
         * @return 是否还在动（需要重绘）。吸附到目标后返回 false 且 `out == (target, 0)`
         */
        fun step(x: Float, v: Float, target: Float, out: FloatArray): Boolean {
            val a = x - target
            val b = (v + zetaOmega * a) / omegaD
            val ac = a * cosWd
            val bs = b * sinWd
            val xd = decay * (ac + bs)
            val vd = decay * (omegaD * (b * cosWd - a * sinWd) - zetaOmega * (ac + bs))
            var nx = target + xd
            var nv = vd
            if (!nx.isFinite() || !nv.isFinite()) {
                // 非有限输入绝不传染到画布（与 push 的 NaN 防御同一条纪律）。
                nx = target
                nv = 0f
            }
            // 剩余行程（位移 + 速度折算的位移）小于阈值 ⇒ 精确吸附。
            if (abs(nx - target) + abs(nv) / omega < SETTLE_EPSILON) {
                out[0] = target
                out[1] = 0f
            } else {
                out[0] = nx
                out[1] = nv
            }
            return out[0] != x || out[1] != v
        }
    }

    /**
     * 小球（质点）的自由落体 + 与柱顶（地面）的弹性碰撞推进器。
     *
     * 与 [SpringStep] 一样：实例在构造期创建，字段零分配。
     */
    class BallStep {
        /**
         * 推进一格。
         *
         * @param y 位置（归一化高度，向上为正）
         * @param v 速度（高度/秒，向上为正）
         * @param resting 上一帧是否静止在地面上
         * @param ground 地面 = 该格柱高的画面值
         * @param groundV 地面的速度（柱高弹簧的速度，向上为正）
         * @param out 长度 ≥ 3 的复用数组：`out[0]` 位置、`out[1]` 速度、`out[2]` 静止标志（0/1）
         * @return 是否发生了位移或速度变化（需要重绘）
         */
        fun step(
            y: Float,
            v: Float,
            resting: Boolean,
            ground: Float,
            groundV: Float,
            dtSec: Float,
            out: FloatArray,
        ): Boolean {
            val g = GRAVITY
            val dt = if (dtSec.isFinite()) dtSec.coerceIn(0f, MAX_DT_SEC) else 0f
            // 先净化地面：非有限的地面会在下面被当成初值用（NaN 传染的入口）。
            val gr = if (ground.isFinite()) ground else 0f
            val gv = if (groundV.isFinite()) groundV else 0f
            var yy = if (y.isFinite()) y else gr
            var vv = if (v.isFinite()) v else 0f

            // ── 1) 静止在地面上：地面的法向力抵消重力，位置跟着地面走 ──
            //    只有"地面塌下去"或"地面快速顶上来"才会让小球重新动起来。
            //
            // ★ v3.4.6：判据从 `resting && yy − gr <= GROUND_EPS` 改成**只看 `resting`**。
            //   旧写法用的是一个 **1e-3 的位置容差**，而地面每帧回落超过 1e-3 时
            //   （回落阶段轻松越过），小球相对新地面就已经"离地超过容差" ⇒ 这一支
            //   永远进不去 ⇒ 小球只能一帧一帧地微落、**永远落不回柱顶**
            //   （单测实测：该停在 0.4，实际停在 0.4006，且永远不吸附）。
            //   而 `resting` 标志本身的语义就是"贴着地面"：它只在
            //   ①"托着走"分支、②碰撞后顶点不可见的吸附分支 里被置 1，
            //   两处都把位置精确写成了地面。所以再按位置判一次既多余、又有上面那个副作用。
            if (resting) {
                if (gv > KICK_MIN_V) {
                    // 地面以可观速度顶上来 ⇒ 被顶起（这正是"弹起来"的来源）。
                    yy = gr
                    vv = if (gv < V_KICK_MAX) gv else V_KICK_MAX
                    out[0] = yy
                    out[1] = vv
                    out[2] = 0f
                    return yy != y || vv != v
                }
                if (gv < -DETACH_MIN_V) {
                    // ★ v3.4.6：**地面塌下去 ⇒ 小球脱离地面**。
                    //
                    //   旧实现在这里走下面的"托着走"分支（位置 = 地面、速度 = 0），
                    //   于是柱子一落，小球就被刚体平移着一起下去 —— 用户实测原话
                    //   「就是粘在顶上一起平移…一点都不真实」。
                    //
                    //   物理上柱顶只能**推**小球、不能**拉**它：地面下落得比自由落体
                    //   还快时，小球必须留在原处开始下落。这里只做"脱离"这一件事
                    //   （位置贴住当前地面、速度归零、清掉静止标志），**本帧不再叠加
                    //   重力** —— 否则本帧就会被第 3 步的碰撞分支夹回地面、脱离失败，
                    //   下一帧起才真正开始自由落体（一帧的延迟，肉眼不可见）。
                    //
                    //   返回"小球有没有真的动"：脱离时地面已经下落，所以 `gr != y` 为真
                    //   （与上面那条"不许因标志翻转就报 true"同一条纪律 —— 只有画面真的
                    //   变了才排帧；标志翻转本身会在下一帧被自由落体如实体现）。
                    out[0] = gr
                    out[1] = 0f
                    out[2] = 0f
                    return gr != y
                }
                // 缓慢移动的地面：小球被托着走，速度保持 0（保证最终能停住）。
                out[0] = gr
                out[1] = 0f
                out[2] = 1f
                return gr != y
            }
            // 地面塌到小球下方（或本来就在空中）⇒ 从当前位置自由落体。

            // ── 2) 自由落体 + **在接触时刻**处理碰撞（解析解，不是"穿模后再夹回来"）──
            //
            // v3.4.6：这一步是本次最重要的修正。旧写法是
            //   ① 整帧积分 `y += v·dt`；② 若 `y <= ground` 就把 y **夹回** ground，
            //      再对**夹回之后**的速度做 `v ← −e·v`。
            // 第 ② 步把小球从地面**以下**瞬移回地面，等于凭空给了它
            // `½·g·穿透深度` 的势能 —— **每帧注入、每跳只衰减 `e²`**，于是存在一个
            // 稳定的极限环：
            //
            //     h* = e²·inj / (1 − e²)
            //
            // e = 0.7 时 `h* ≈ 0.6%` 满幅，**远高于** [REST_APEX]（0.15%）⇒
            // 小球会在柱顶上永远微跳、永不吸附（单测实测：该停在 0.4，
            // 实际在 0.4006±0.006 之间循环 600 帧都不停）。
            // 旧值 e = 0.45 只是**刚好**把 h* 压到 REST_APEX 以下（≈0.00155）才没暴露 ——
            // 也就是说旧实现一直站在这个坑的边上，而"能吸附"是靠参数凑出来的，不是靠算法。
            //
            // 现在改成求**接触时刻** `t*`：解 `y₀ + v·t − ½g·t² = ground`，取最小非负根
            //
            //     t* = (v + √(v² + 2g·d₀)) / g,   d₀ = y₀ − ground ≥ 0
            //
            // 碰撞发生在地面**上**，没有瞬移 ⇒ 不再注入能量 ⇒ 吸附由 [REST_APEX]
            // 这条真正的判据决定，与 e 取值无关（e 只决定"看得到几跳"）。
            // 顺带它也让弹道对 dt 精确（旧写法在接触帧的长度与刷新率有关）。
            val d0 = yy - gr
            val tHit: Float = if (d0 <= 0f) {
                0f
            } else {
                val disc = vv * vv + 2f * g * d0
                if (disc <= 0f) Float.MAX_VALUE else (vv + sqrt(disc)) / g
            }

            if (tHit < dt) {
                // ── 2a) 本帧内撞地 ──
                val vHit = vv - g * tHit
                var vOut = if (vHit < 0f) -RESTITUTION * vHit else vHit
                // 地面正在上升 ⇒ 把小球顶起来（正碰）。这一条对两种情况都成立：
                // 接住正在下落的球、以及追上正在上升的球。上限只加在这一项上。
                if (gv > vOut) {
                    val kick = if (gv < V_KICK_MAX) gv else V_KICK_MAX
                    if (kick > vOut) vOut = kick
                }
                // 顶点看不见 ⇒ 吸附静止。用**顶点**而不是速度阈值，才能与刷新率无关。
                val rest = vOut * vOut < 2f * g * REST_APEX
                if (rest) {
                    yy = gr
                    vv = 0f
                    out[0] = yy
                    out[1] = vv
                    out[2] = 1f
                    // ⚠️ 只能按"小球有没有真的动"报变化，**不能**因为静止标志翻转就报 true。
                    //    后者会让"从未 push 过"的环形缓冲（`peakRest` 初值全 false、
                    //    小球与地面都在 0）在第一帧就要求重绘，直接打破「不空转」契约 ——
                    //    单测 `不播放时不推进相位 —— 不空转` / `静音时不推进相位也不要求重绘`
                    //    抓到的就是这个。
                    return yy != y || vv != v
                }
                // 碰撞之后的剩余时间继续走（常加速度精确解）。
                val dt2 = dt - tHit
                yy = gr + vOut * dt2 - 0.5f * g * dt2 * dt2
                vv = vOut - g * dt2
            } else {
                // ── 2b) 本帧没撞地：整帧自由落体 ──
                yy += vv * dt - 0.5f * g * dt * dt
                vv -= g * dt
            }

            // ── 3) 硬契约：小球绝不低于当前柱高 ──
            //    正常情况下 2a 已经保证了这一点（碰撞发生在地面上）；这里只兜住
            //    ① dt 极大（卡顿后 `MAX_DT_SEC = 0.2`）时一跳在帧内走完、
            //    ② 地面在小球下落期间上升到它上方 这两种边界。
            var rest = false
            if (yy <= gr) {
                yy = gr
                if (vv < 0f) vv = 0f
                if (vv * vv < 2f * g * REST_APEX) {
                    vv = 0f
                    rest = true
                }
            }
            out[0] = yy
            out[1] = vv
            out[2] = if (rest) 1f else 0f
            return yy != y || vv != v
        }
    }

    // v3.4.6：原来的 `GROUND_EPS`（= 1e-3 的**位置**容差）已删除。
    //
    // 它只被"小球是否还贴在地面上"那条判据用过，而那条判据现在只看 `resting` 标志
    // （理由见 [BallStep.step] 里的那一段注释：位置容差会让地面一回落就再也进不去
    // 静止分支，小球于是永远吸附不到柱顶）。留着它就是一段没人读的常数 —— 删掉比
    // 留一段死代码更诚实。**不要再把它加回来**。

    // ───────────────────────── 峰值短横：真正的峰值保持 ─────────────────────────

    /**
     * v3.4.6：峰值短横的**回落速度**（归一化高度/秒）。
     *
     * ## 为什么短横要单独一份状态
     *
     * 在它之前，短横的位置是 `小球位置 + 常量(2r+cap)`（见 `BandMarkerGeometry`）——
     * 也就是它和小球**永远同步移动**，只是一条被抬高的影子。用户实测两次指出这一点：
     * 「它和小短线是一样的」「短线也是[粘在顶上一起平移]」。
     *
     * 而它自己的 KDoc 一直写着它是「**这一格曾经到过的最高点**」，小球是「此刻的质点」——
     * 实现与声明不符。现在补上这份状态：短横 = 小球位置的**历史最大值**（带缓慢回落），
     * 于是两者终于各说各的话：小球弹，短横压着它到过的最高处慢慢下来。
     *
     * ## 取值 0.5 /s
     *
     * 从满幅 1.0 回落到 0 用 **2 秒**。参照系是柱间隔（真机 ~100ms）：
     * 2s ≈ 20 根柱，所以短横记的是"最近这一小段"的峰值，而不是永久贴在天花板上
     * （`0` 会让它永远留在历史最高点，整条线会僵在画面上方）。
     * 逐帧回落量 `0.5 × 1/60 ≈ 0.0083`，肉眼是一段平滑下滑，不是跳变。
     */
    const val DASH_HOLD_DECAY_PER_SEC = 0.5f

    /**
     * 峰值保持一步：`hold ← max(小球, hold − 回落速度 × dt)`，并夹到 `≥ 0`。
     *
     * 三条不变量（都有单测）：
     * 1. **短横绝不低于小球** —— 否则"历史峰值"会画到质点的下面，读起来是错的；
     * 2. **绝不为负** —— 归一化高度域的硬契约（柱高、小球都是 `[0,1]`）；
     * 3. **小球上去它立刻跟上**（同一帧），下落时按固定速度线性回落 —— 不用指数衰减，
     *    因为线性的"每秒掉多少"可以直接与柱间隔比较，调参时不用换算时间常数。
     *
     * 非有限输入一律归零，与 [BallStep] / [SpringStep] 同一条纪律。
     */
    fun holdStep(ball: Float, hold: Float, dtSec: Float): Float {
        if (!ball.isFinite() || !hold.isFinite()) return 0f
        val dt = if (dtSec.isFinite()) dtSec.coerceIn(0f, MAX_DT_SEC) else 0f
        val decayed = hold - DASH_HOLD_DECAY_PER_SEC * dt
        return maxOf(ball, decayed, 0f)
    }
}
