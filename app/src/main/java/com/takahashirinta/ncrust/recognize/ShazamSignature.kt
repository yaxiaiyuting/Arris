    /** 从 16 kHz 单声道 f32（-1..1）生成签名二进制。 */
    fun generateFromF32(buffer: FloatArray): ByteArray {
        val s16 = ShortArray(buffer.size) { i ->
            // 与 rodio SampleTypeConverter::<f32,i16> 等价：先 ×32767，再截断
            (buffer[i] * 32767.0f).toInt().toShort()
        }
        return generateFromPcm16(s16)
    }

    /** 从 16 kHz 单声道 PCM16 生成签名二进制。 */
    fun generateFromPcm16(samples: ShortArray): ByteArray {
        val fftOutputs = Array(RING) { FloatArray(BINS) }
        val spreadOutputs = Array(RING) { FloatArray(BINS) }
        val peaks = Array(BAND_RANGES.size) { ArrayList<Peak>(64) }
        val ring = ShortArray(WINDOW)
        val reordered = FloatArray(WINDOW)
        val re = FloatArray(WINDOW)
        val im = FloatArray(WINDOW)
        var ringIndex = 0
        var fftIndex = 0
        var spreadIndex = 0
        var spreadDone = 0

        for (chunkStart in samples.indices step HOP) {
            // 复制 128 个样本进环形缓冲（不足则补零，与 Rust 的 as_chunks 行为一致：末尾不足 128 丢弃）
            if (chunkStart + HOP > samples.size) break
            for (i in 0 until HOP) ring[ringIndex + i] = samples[chunkStart + i]
            ringIndex = (ringIndex + HOP) and (WINDOW - 1)

            // 重排 + 汉宁窗
            for (i in 0 until WINDOW) {
                reordered[i] = ring[(i + ringIndex) and (WINDOW - 1)].toFloat() * HANNING[i]
            }

            // 实数 FFT：复数 FFT 后取前 1025 个 bin
            reordered.copyInto(re)
            im.fill(0f)
            fft(re, im)
            val out = fftOutputs[fftIndex]
            for (bin in 0 until BINS) {
                val mag = (re[bin] * re[bin] + im[bin] * im[bin]) / 131072.0f
                out[bin] = max(mag, 1e-10f)
            }
            fftIndex = (fftIndex + 1) and (RING - 1)

            // ---- do_peak_spreading ----
            val real = fftOutputs[(fftIndex - 1) and (RING - 1)]
            val spread = spreadOutputs[spreadIndex]
            real.copyInto(spread)
            for (p in 0..1022) {
                spread[p] = max(spread[p], max(spread[p + 1], spread[p + 2]))
            }
            val snapshot = spread.copyOf()
            for (p in 0..1024) {
                for (former in intArrayOf(1, 3, 6)) {
                    val prev = spreadOutputs[(spreadIndex - former) and (RING - 1)]
                    if (prev[p] < snapshot[p]) prev[p] = snapshot[p]
                }
            }
            spreadIndex = (spreadIndex + 1) and (RING - 1)
            spreadDone += 1

            if (spreadDone >= 46) {
                collectPeaks(
                    fftMinus46 = fftOutputs[(fftIndex - 46) and (RING - 1)],
                    spreadMinus49 = spreadOutputs[(spreadIndex - 49) and (RING - 1)],
                    spreadOutputs = spreadOutputs,
                    spreadIndex = spreadIndex,
                    passNumber = spreadDone - 46,
                    peaks = peaks,
                )
            }
        }

        return encode(peaks, samples.size)
    }

    private class Peak(val passNumber: Int, val magnitude: Int, val correctedBin: Int)

    private val NEIGHBOR_OFFSETS = intArrayOf(-10, -7, -4, -3, 1, 2, 5, 8)
    private val TIME_OFFSETS = intArrayOf(-53, -45, 165, 172, 179, 186, 193, 200, 214, 221, 228, 235, 242, 249)

    private fun collectPeaks(
        fftMinus46: FloatArray,
        spreadMinus49: FloatArray,
        spreadOutputs: Array<FloatArray>,
        spreadIndex: Int,
        passNumber: Int,
        peaks: Array<ArrayList<Peak>>,
    ) {
        for (bin in 10..1014) {
            val value = fftMinus46[bin]
            if (value < 1.0f / 64.0f) continue
            if (value < spreadMinus49[bin - 1]) continue

            var maxNeighbor = 0f
            for (off in NEIGHBOR_OFFSETS) maxNeighbor = max(maxNeighbor, spreadMinus49[bin + off])
            if (value <= maxNeighbor) continue

            var maxOther = maxNeighbor
            for (off in TIME_OFFSETS) {
                val other = spreadOutputs[(spreadIndex + off) and (RING - 1)]
                maxOther = max(maxOther, other[bin - 1])
            }
            if (value <= maxOther) continue

            val m = magnitude(value)
            val mBefore = magnitude(fftMinus46[bin - 1])
            val mAfter = magnitude(fftMinus46[bin + 1])
            val var1 = m * 2f - mBefore - mAfter
            if (var1 < 0f) continue
            val var2 = (mAfter - mBefore) * 32f / var1
            val corrected = (bin * 64) + var2.toInt()
            val frequencyHz = corrected.toFloat() * (SAMPLE_RATE / 2f / 1024f / 64f)
            val band = BAND_RANGES.indexOfFirst { frequencyHz.toInt() in it }
            if (band < 0) continue
            // Rust 的 `f32 as u16` 是**饱和转换**（越界夹到 0/65535），Kotlin 的 toInt() 会回绕。
            // 实测差异就出在这里：2312 字节里有 3 个字节不同，全是超强峰值/极大 bin 的回绕。
            val magnitudeU16 = m.coerceIn(0f, 65535f).toInt()
            val correctedU16 = corrected.coerceIn(0, 65535)
            peaks[band].add(Peak(passNumber, magnitudeU16, correctedU16))
        }
    }

    private fun magnitude(v: Float): Float = ln(max(v, 1f / 64f)) * 1477.3f + 6144f

    /** `encode_to_binary` 的等价实现。 */
    private fun encode(peaks: Array<ArrayList<Peak>>, numberSamples: Int): ByteArray {
        val out = ByteArrayOutputStream(4096)
        fun u32(v: Int) { out.write(v and 0xFF); out.write((v ushr 8) and 0xFF); out.write((v ushr 16) and 0xFF); out.write((v ushr 24) and 0xFF) }
        fun u16(v: Int) { out.write(v and 0xFF); out.write((v ushr 8) and 0xFF) }

        u32(0xcafe2580.toInt())
        u32(0) // crc32 占位
        u32(0) // size_minus_header 占位
        u32(0x94119c00.toInt())
        u32(0); u32(0); u32(0)
        u32(3 shl 27) // sample rate id：16000 → 3
        u32(0); u32(0)
        u32(numberSamples + (SAMPLE_RATE * 0.24f).toInt())
        u32((15 shl 19) + 0x40000)
        u32(0x40000000)
        u32(0) // size_minus_header 占位（第二处）

        peaks.forEachIndexed { band, list ->
            if (list.isEmpty()) return@forEachIndexed
            val buf = ByteArrayOutputStream(list.size * 5)
            var lastPass = 0
            for (peak in list) {
                if (peak.passNumber - lastPass >= 255) {
                    buf.write(0xFF)
                    buf.write(peak.passNumber and 0xFF)
                    buf.write((peak.passNumber ushr 8) and 0xFF)
                    buf.write((peak.passNumber ushr 16) and 0xFF)
                    buf.write((peak.passNumber ushr 24) and 0xFF)
                    lastPass = peak.passNumber
                }
                buf.write((peak.passNumber - lastPass) and 0xFF)
                buf.write(peak.magnitude and 0xFF); buf.write((peak.magnitude ushr 8) and 0xFF)
                buf.write(peak.correctedBin and 0xFF); buf.write((peak.correctedBin ushr 8) and 0xFF)
                lastPass = peak.passNumber
            }
            val bytes = buf.toByteArray()
            u32(0x60030040 + band)
            u32(bytes.size)
            out.write(bytes)
            val pad = (4 - bytes.size % 4) % 4
            repeat(pad) { out.write(0) }
        }

        val all = out.toByteArray()
        val sizeMinusHeader = all.size - 48
        writeU32(all, 8, sizeMinusHeader)
        writeU32(all, 52, sizeMinusHeader)
        val crc = CRC32().apply { update(all, 8, all.size - 8) }.value.toInt()
        writeU32(all, 4, crc)
        return all
    }

    private fun writeU32(arr: ByteArray, offset: Int, v: Int) {
        arr[offset] = (v and 0xFF).toByte()
        arr[offset + 1] = ((v ushr 8) and 0xFF).toByte()
        arr[offset + 2] = ((v ushr 16) and 0xFF).toByte()
        arr[offset + 3] = ((v ushr 24) and 0xFF).toByte()
    }

    /**
     * 原地复数 FFT（基 2，长度必须为 2 的幂）。
     *
     * 旋转因子**逐点现算**（用 double 的 cos/sin 再降到 float），不用递推 —— 递推会累积误差，
     * 而这里和 SongRec（rustfft）比对时，误差正好落在峰值判定的 `>=` 边界上：
     * 2312 字节里有 3 个峰的 pass 序号差 1。
     */
    private fun fft(re: FloatArray, im: FloatArray) {
        val n = re.size
        var j = 0
        for (i in 1 until n) {
            var bit = n shr 1
            while (j and bit != 0) { j = j xor bit; bit = bit shr 1 }
            j = j or bit
            if (i < j) {
                var t = re[i]; re[i] = re[j]; re[j] = t
                t = im[i]; im[i] = im[j]; im[j] = t
            }
        }
        var len = 2
        while (len <= n) {
            val half = len / 2
            var k = 0
            while (k < half) {
                val angle = -2.0 * Math.PI * k / len
                val wr = cos(angle).toFloat()
                val wi = kotlin.math.sin(angle).toFloat()
                var i = 0
                while (i < n) {
                    val a = i + k
                    val b = a + half
                    val vr = re[b] * wr - im[b] * wi
                    val vi = re[b] * wi + im[b] * wr
                    val ur = re[a]
                    val ui = im[a]
                    re[a] = ur + vr; im[a] = ui + vi
                    re[b] = ur - vr; im[b] = ui - vi
                    i += len
                }
                k++
            }
            len = len shl 1
        }
    }

    /** 供自检：把签名按 zlib+base64 编码成接口要求的 `rawdata`。 */
    fun toRawdata(signature: ByteArray): String {
        val deflater = java.util.zip.Deflater(java.util.zip.Deflater.DEFAULT_COMPRESSION, false)
        deflater.setInput(signature); deflater.finish()
        val out = ByteArrayOutputStream(signature.size / 2 + 64)
        val buf = ByteArray(8192)
        while (!deflater.finished()) {
            val n = deflater.deflate(buf)
            if (n > 0) out.write(buf, 0, n)
        }
        deflater.end()
        return java.util.Base64.getEncoder().encodeToString(out.toByteArray())
    }
